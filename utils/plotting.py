# ---------------------------------------------------------------------------
#  The rollout: animate the robot following its optimal policy (MP4, headless).
# ---------------------------------------------------------------------------
def _q_value(env, V, s, a, gamma):
    return sum(p * (r + gamma * V[s2]) for p, s2, r in env.transitions(s, a))


def rollout(env, policy, seed=0, max_steps=400):
    """Follow the greedy policy from the start; return the list of visited states."""
    return [t["s"] for t in rollout_trace(env, None, policy, 0.0, seed, max_steps)]


def rollout_trace(env, V, policy, gamma, seed=0, max_steps=400):
    """Play one episode under the policy and record, at every step, the information
    a student needs to understand and debug the run: the value of the current cell,
    the action value q(s, a) of each of the four moves, which move the policy took,
    which move actually has the highest q, the reward, the running return, and
    whether the floor made the robot slip."""
    rng = np.random.default_rng(seed)
    s = env.start_state
    ret, disc, trace = 0.0, 1.0, []
    for _ in range(max_steps):
        r, c, hp = env.decode(s)
        if env.is_terminal(s):
            trace.append(dict(s=s, r=r, c=c, hp=hp, term=True, Vs=0.0, qs={},
                              action=None, best=None, reward=None, ret=ret, slipped=False))
            break
        a = max(policy[s], key=policy[s].get)
        qs = ({aa: _q_value(env, V, s, aa, gamma) for aa in env.actions}
              if V is not None else {})
        best = max(qs, key=qs.get) if qs else a
        outs = env.transitions(s, a)
        intended = max(outs, key=lambda o: o[0])[1]
        j = rng.choice(len(outs), p=[p for p, _, _ in outs])
        _, s2, rew = outs[j]
        slipped = len(outs) > 1 and s2 != intended
        ret += disc * rew
        trace.append(dict(s=s, r=r, c=c, hp=hp, term=False,
                          Vs=(float(V[s]) if V is not None else 0.0), qs=qs,
                          action=a, best=best, reward=rew, ret=ret, slipped=slipped))
        disc *= gamma
        s = s2
    return trace


def _panel_legend(axp):
    """Static key of the symbols, drawn once on the info panel."""
    axp.text(0.5, 0.985, "What the robot sees", ha="center", va="top",
             fontsize=13, fontweight="bold", color=PALETTE["accent"])
    axp.text(0.04, 0.235, "symbols", fontsize=9.5, fontweight="bold",
             color=PALETTE["slate"])
    items = [("house", "start / depot"), ("star", "goal / door"),
             ("triangle", "hazard (ends run)"), ("box", "package pickup"),
             ("dots", "rough (costs more)"), ("waves", "slippery floor")]
    for i, (sym, label) in enumerate(items):
        yy = 0.19 - i * 0.033
        axp.text(0.08, yy, {"house": "⌂", "star": "★", "triangle": "⚠",
                 "box": "■", "dots": "∴", "waves": "≈"}[sym],
                 fontsize=11, ha="center", va="center", color=PALETTE["ink"])
        axp.text(0.16, yy, label, fontsize=9.5, va="center", color=PALETTE["slate"])


def _render_bg_array(env, V, policy, hp, ppc=38):
    """Render the maze (values, arrows, icons) once to an RGBA image. The rollout
    video then shows this image and only animates the robot on top, so a long
    episode renders quickly instead of redrawing hundreds of cells every frame."""
    figb = plt.figure(figsize=(env.n_cols * ppc / 100.0, env.n_rows * ppc / 100.0),
                      dpi=100)
    axb = figb.add_axes([0, 0, 1, 1])
    _draw_layer(axb, env, V, policy, hp, "")
    axb.set_title("")
    axb.set_xlim(-0.5, env.n_cols - 0.5)
    axb.set_ylim(env.n_rows - 0.5, -0.5)
    axb.axis("off")
    figb.canvas.draw()
    w, h = figb.canvas.get_width_height()
    buf = np.asarray(figb.canvas.buffer_rgba()).reshape(h, w, 4).copy()
    plt.close(figb)
    return buf


def figure_rollout(env, V, policy, name="rollout.mp4", seed=0, fps=10, max_frames=700):
    """Animate one rollout with a live annotation panel (value, the four action
    values, the move taken, the reward and running return) and save it as an MP4
    video, one frame per step. Needs ffmpeg (the rl environment installs it); falls
    back to a GIF, then to a PNG filmstrip, so it never hard-fails."""
    from matplotlib import animation

    gamma = getattr(env, "gamma", 0.98)
    trace = rollout_trace(env, V, policy, gamma, seed=seed)
    sel = (sorted(set(np.linspace(0, len(trace) - 1, max_frames).astype(int)))
           if len(trace) > max_frames else list(range(len(trace))))

    # pre-render the maze background(s) as images (fast frames for long episodes)
    bg = {0: _render_bg_array(env, V, policy, 0)}
    bg[1] = _render_bg_array(env, V, policy, 1) if env.has_package_dim else bg[0]
    extent = [-0.5, env.n_cols - 0.5, env.n_rows - 0.5, -0.5]

    fig, (axm, axp) = plt.subplots(
        1, 2, figsize=(2.0 + 0.30 * (env.n_cols + 12), 1.4 + 0.30 * env.n_rows),
        dpi=90, gridspec_kw={"width_ratios": [env.n_cols, 12]})
    axm.axis("off")
    imbg = axm.imshow(bg[0], extent=extent, aspect="auto", zorder=0,
                      interpolation="antialiased")
    axm.set_xlim(-0.5, env.n_cols - 0.5)
    axm.set_ylim(env.n_rows - 0.5, -0.5)
    trail, = axm.plot([], [], "-", color=PALETTE["ink"], alpha=0.5, lw=2.2, zorder=3)
    axp.axis("off")
    axp.set_xlim(0, 1)
    axp.set_ylim(0, 1)
    _panel_legend(axp)
    keep = {id(imbg), id(trail)}
    cur = {"hp": 0}
    ARROW_CH = {"up": "↑", "down": "↓", "left": "←", "right": "→"}
    ink, slate = PALETTE["ink"], PALETTE["slate"]

    # Create the panel text objects ONCE and update them each frame (fast).
    t_step = axp.text(0.04, 0.90, "", fontsize=12, fontweight="bold", color=ink)
    t_carry = axp.text(0.55, 0.90, "", fontsize=11, color=ink)
    t_v = axp.text(0.04, 0.81, "", fontsize=11, color=ink)
    t_qh = axp.text(0.04, 0.72, "action values  q(s, a):", fontsize=11,
                    fontweight="bold", color=PALETTE["accent"])
    tq, ttag = [], []
    for k in range(len(env.actions)):
        yy = 0.65 - k * 0.058
        tq.append(axp.text(0.08, yy, "", fontsize=11, family="monospace", color=slate))
        ttag.append(axp.text(0.52, yy, "", fontsize=9.5, va="center", color=slate))
    t_mm = axp.text(0.04, 0.42, "", fontsize=9.5, color=PALETTE["bad"])
    t_rew = axp.text(0.04, 0.37, "", fontsize=11, color=ink)
    t_ret = axp.text(0.04, 0.33, "", fontsize=11, color=ink)
    t_slip = axp.text(0.04, 0.29, "", fontsize=10, fontweight="bold", color=PALETTE["orange"])
    t_term = axp.text(0.04, 0.80, "", fontsize=13, fontweight="bold")
    t_tret = axp.text(0.04, 0.70, "", fontsize=11, color=ink)
    normal = [t_v, t_qh, *tq, *ttag, t_mm, t_rew, t_ret, t_slip]

    def draw(i):
        info = trace[sel[i]]
        hp = info["hp"]
        if hp != cur["hp"]:
            imbg.set_data(bg[hp])
            cur["hp"] = hp
        for coll in (axm.patches, axm.lines, axm.texts):
            for art in list(coll):
                if id(art) not in keep:
                    art.remove()
        axm.set_title(f"step {sel[i]}    "
                      f"({'carrying package' if hp else 'no package'})",
                      fontsize=12, fontweight="bold")
        seg = [(e["c"], e["r"]) for e in trace[:sel[i] + 1] if e["hp"] == hp]
        if seg:
            xs, ys = zip(*seg)
            trail.set_data(xs, ys)
        _icon(axm, info["r"], info["c"], "robot")

        # info panel (update text in place)
        t_step.set_text(f"step {sel[i]}")
        t_carry.set_text("carrying: " + ("yes" if hp else "no"))
        term = info["term"]
        for obj in normal:
            obj.set_visible(not term)
        t_term.set_visible(term)
        t_tret.set_visible(term)
        if term:
            goal = env.tile(info["r"], info["c"]) == "G"
            t_term.set_text("DELIVERED" if goal else "hit a hazard")
            t_term.set_color(PALETTE["good"] if goal else PALETTE["bad"])
            t_tret.set_text(f"total return = {info['ret']:.1f}")
            return
        t_v.set_text(f"value of this cell   V = {info['Vs']:.1f}")
        for k, a in enumerate(env.actions):
            chosen = (a == info["action"])
            col = PALETTE["vermillion"] if chosen else slate
