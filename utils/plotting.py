# ---------------------------------------------------------------------------
#  PI vs VI convergence race (sup-norm error to V* vs Bellman sweeps).
# ---------------------------------------------------------------------------
def figure_pi_vs_vi(vi_err, pi_x, pi_err, name="pi_vs_vi.png"):
    fig, ax = plt.subplots(figsize=(8.4, 4.4))
    ax.semilogy(np.arange(1, len(vi_err) + 1), vi_err, "o-", color=PALETTE["blue"],
                ms=3, lw=1.4, label="value iteration (1 sweep per step)")
    ax.semilogy(pi_x, pi_err, "s-", color=PALETTE["orange"], ms=7, lw=1.4,
                mfc="none", label="policy iteration (full evaluation per step)")
    ax.set_xlabel("cumulative Bellman sweeps over the state space")
    ax.set_ylabel(r"max error to $V_*$ (log scale)")
    ax.set_title("Policy iteration takes a few expensive steps; value iteration many cheap ones")
    ax.legend()
    return _save(fig, name)


