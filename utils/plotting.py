def _value_grid(env, V, hp):
    """Reshape V (for one has_package layer) into a (rows, cols) array; walls NaN."""
    grid = np.full((env.n_rows, env.n_cols), np.nan)
    for r in range(env.n_rows):
        for c in range(env.n_cols):
            if not env.is_wall(r, c):
                grid[r, c] = V[env.encode(r, c, hp)]
    return grid


def _draw_layer(ax, env, V, policy, hp, title, show_values=True):
    grid = _value_grid(env, V, hp)
    finite = grid[np.isfinite(grid)]
    lo, hi = float(np.min(finite)), float(np.max(finite))
    norm = TwoSlopeNorm(vmin=min(lo, -0.1), vcenter=0.0, vmax=max(hi, 0.1))
    show_text = show_values and env.n_rows * env.n_cols <= 90

    masked = np.ma.masked_invalid(grid)
    cmap = VALUE_CMAP.copy()
    cmap.set_bad(PALETTE["slate"])  # walls
    ax.imshow(masked, cmap=cmap, norm=norm, origin="upper")

    icon_of = {"S": "depot", "G": "goal", "H": "hazard", "P": "parcel"}
    for r in range(env.n_rows):
        for c in range(env.n_cols):
            t = env.tile(r, c)
            if t == "#":
                continue
            s = env.encode(r, c, hp)
            # a faint tile-colour wash for the goal (gold) and hazard (orange)
            if t == "G":
                ax.add_patch(Rectangle((c - 0.5, r - 0.5), 1, 1, facecolor=GOLD,
                             alpha=0.18, zorder=1))
            elif t == "H":
                ax.add_patch(Rectangle((c - 0.5, r - 0.5), 1, 1,
                             facecolor=PALETTE["orange"], alpha=0.18, zorder=1))
            elif t == "R":
                _rough_dots(ax, r, c)
            elif t == "~":
                _slip_wave(ax, r, c)

            special = t in icon_of
            if special:
                _icon(ax, r, c, icon_of[t])
            else:
                # policy arrow on ordinary floor (skip terminals)
                if policy is not None and s in policy and not env.is_terminal(s):
                    a = max(policy[s], key=policy[s].get)
                    dx, dy = ARROW[a]
                    ax.arrow(c, r - 0.05, dx * 0.30, dy * 0.30, head_width=0.22,
                             head_length=0.20, lw=2.4, fc=PALETTE["vermillion"],
                             ec=PALETTE["vermillion"], length_includes_head=True,
                             zorder=3)
                if show_text and not env.is_terminal(s):
                    ax.text(c, r + 0.34, f"{grid[r, c]:.0f}", ha="center", va="center",
                            fontsize=10, color=PALETTE["ink"], zorder=3)
    ax.set_xticks([]); ax.set_yticks([]); ax.grid(False)
    ax.set_title(title, fontsize=14, fontweight="bold")


def figure_value_policy(env, V, policy, name, title=""):
    """Value heatmap + greedy arrows. Two panels if the world tracks the package."""
    if env.has_package_dim:
        fig, axes = plt.subplots(1, 2, figsize=(2.0 + 1.05 * env.n_cols * 2, 1.4 + 0.95 * env.n_rows))
        _draw_layer(axes[0], env, V, policy, 0, "before pickup (no package)")
        _draw_layer(axes[1], env, V, policy, 1, "after pickup (carrying package)")
        fig.suptitle(title, fontsize=13, fontweight="bold", y=1.04)
    else:
        fig, ax = plt.subplots(figsize=(1.6 + 1.05 * env.n_cols, 1.2 + 0.95 * env.n_rows))
        _draw_layer(ax, env, V, policy, 0, title)
    return _save(fig, name)


