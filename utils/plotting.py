def _filmstrip(env, V, policy, path, name):
    picks = np.unique(np.linspace(0, len(path) - 1, min(6, len(path))).astype(int))
    fig, axes = plt.subplots(1, len(picks), figsize=(2.4 * len(picks), 2.6))
    if len(picks) == 1:
        axes = [axes]
    for ax, frame in zip(axes, picks):
        r, c, hp = env.decode(path[frame])
        _draw_layer(ax, env, V, policy, hp, f"step {frame}")
        ax.plot(c, r, "o", ms=12, color=PALETTE["vermillion"],
                markeredgecolor="white", markeredgewidth=1.2)
    return _save(fig, name)


